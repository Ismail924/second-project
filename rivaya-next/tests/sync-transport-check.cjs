const assert=require('node:assert/strict');
const {Transport}=require('../app/src/main/assets/sync-transport.js');
const owner='957bb432-19d3-4ae1-a450-89743073d276';
const other='84ceda97-4e0a-4a8a-8f20-8d694a55142f';
const document={schemaVersion:1,goals:[],habits:[],checks:{},profile:{name:'A'},preferences:{stepGoal:9000}};
const response=(data,status=200)=>({ok:status<300,status,json:async()=>data});
const setup=fetch=>new Transport({url:'https://example.supabase.co',publishableKey:'sb_publishable_test',session:async()=>({userId:owner,accessToken:'test-only'}),fetch});
const rejects=(promise,code)=>assert.rejects(promise,e=>e.code===code);
(async()=>{
  let sent;
  const t=setup(async(url,options)=>{sent={url,...options};return response(1);});
  assert.equal(await t.push(owner,0,{...document,healthRecords:[123],billing:{pro:true}}),1);
  const body=JSON.parse(sent.body);
  assert.equal(body.expected_revision,0);assert.equal(body.document.preferences.stepGoal,9000);
  assert.equal(body.document.healthRecords,undefined);assert.equal(body.document.billing,undefined);
  assert.equal(sent.headers.Authorization,'Bearer test-only');assert.equal(sent.headers.apikey,'sb_publishable_test');
  assert.equal(sent.redirect,'error');
  await rejects(t.pull(other),'authentication_required');
  assert.equal(await setup(async()=>response([])).pull(owner),null);
  const fetched=await setup(async()=>response([{user_id:owner,revision:3,payload:document}])).pull(owner);
  assert.equal(fetched.revision,3);
  await rejects(setup(async()=>response([{user_id:other,revision:3,payload:document}])).pull(owner),'invalid_response');
  await rejects(setup(async()=>response({code:'40001'},409)).push(owner,2,document),'revision_conflict');
  await rejects(setup(async()=>response({},401)).pull(owner),'authentication_required');
  await rejects(setup(async()=>response({},429)).pull(owner),'rate_limited');
  await rejects(setup(async()=>{throw Error('offline');}).pull(owner),'network_unavailable');
  await rejects(setup(async()=>response(99)).push(owner,2,document),'invalid_response');
  let release,started;
  const ready=new Promise(resolve=>{started=resolve;});
  const delayed=setup(async()=>{started();return new Promise(resolve=>{release=resolve;});});
  const pending=delayed.pull(owner);await ready;delayed.cancel();
  release(response([{user_id:owner,revision:1,payload:document}]));
  await rejects(pending,'cancelled');
  const timeout=setup((url,{signal})=>new Promise((resolve,reject)=>signal.addEventListener('abort',()=>reject(Error('abort')))));
  timeout.timeoutMs=5;await rejects(timeout.pull(owner),'timeout');
  assert.throws(()=>new Transport({url:'http://example.com',publishableKey:'sb_publishable_test',session:()=>null}));
  console.log('PASS: cloud ownership, CAS conflicts, upload allowlist, cancellation, timeout, auth and network failures');
})().catch(error=>{console.error(error);process.exitCode=1;});
